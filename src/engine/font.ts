export interface Glyph {
  w: number;
  rows: Uint8Array[];
}

const glyphs = new Map<string, Glyph>();
for (const [ch, def] of Object.entries(G)) {
  const rowsS = def.split('|');
  const w = Math.max(...rowsS.map((r) => r.length));
  const rows = rowsS.map((r) => {
    const a = new Uint8Array(w);
    for (let i = 0; i < r.length; i++) a[i] = r[i] === '#' ? 1 : 0;
    return a;
  });
  glyphs.set(ch, { w, rows });
}

export const LINE_H = 10;
export const FONT_H = 9;

export function glyph(ch: string): Glyph {
  return glyphs.get(ch) ?? glyphs.get('?')!;
}

export function charWidth(ch: string): number {
  if (ch === ' ') return 3;
  return glyph(ch).w;
}

/** Width in pixels of a single line of text (1px tracking). */
export function textWidth(s: string): number {
  let w = 0;
  for (let i = 0; i < s.length; i++) {
    w += charWidth(s[i]) + 1;
  }
  return Math.max(0, w - 1);
}

/** Word-wrap a string (respecting \n) to fit a pixel width. */
export function wrapText(s: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of s.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const cand = line ? line + ' ' + word : word;
      if (textWidth(cand) <= maxW || !line) {
        // hard-break very long words
        if (textWidth(cand) > maxW && !line) {
          let chunk = '';
          for (const ch of word) {
            if (textWidth(chunk + ch) > maxW) {
              out.push(chunk);
              chunk = ch;
            } else chunk += ch;
          }
          line = chunk;
        } else line = cand;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}

/** Plot callback signature so text can render to any surface. */
export type Plot = (x: number, y: number) => void;

export function renderText(s: string, x: number, y: number, plot: Plot, bold = false): number {
  let cx = x;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === ' ') {
      cx += 4;
      continue;
    }
    const g = glyph(ch);
    for (let ry = 0; ry < g.rows.length; ry++) {
      const row = g.rows[ry];
      for (let rx = 0; rx < g.w; rx++) {
        if (row[rx]) {
          plot(cx + rx, y + ry);
          if (bold) plot(cx + rx + 1, y + ry);
        }
      }
    }
    cx += g.w + 1 + (bold ? 1 : 0);
  }
  return cx - x;
}
